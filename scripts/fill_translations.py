def apply_translations(po_file: str, translations: dict):
    """Read po_file, fill in msgstr for matched msgids, write back."""
    with open(po_file, "r", encoding="utf-8") as f:
        content = f.read()

    # Parse entries: find all msgid / msgstr pairs
    # Strategy: replace empty msgstr "" that follow a known msgid
    count = 0
    for msgid, msgstr in translations.items():
        # Escape special regex characters in msgid for search
        # We look for exact msgid ... msgstr "" pattern
        # Simple approach: split on blocks
        escaped_id = msgid.replace("\\", "\\\\").replace('"', '\\"').replace("\n", '\\n"\n"')
        
        # Pattern to match msgid "..." followed by msgstr ""
        # Handle multiline msgid (rare but possible)
        old = f'msgid "{escaped_id}"\nmsgstr ""'
        new = f'msgid "{escaped_id}"\nmsgstr "{msgstr.replace(chr(92), chr(92)*2).replace(chr(34), chr(92)+chr(34)).replace(chr(10), chr(92)+"n"+chr(10)+chr(34))}"'
        
        if old in content:
            content = content.replace(old, new, 1)
            count += 1

    with open(po_file, "w", encoding="utf-8") as f:
        f.write(content)
    
    print(f"  {po_file}: applied {count}/{len(translations)} translations")


def apply_translations_multiline(po_file: str, translations: dict):
    """
    More robust approach: parse the .po file into entries and fill in translations.
    """
    with open(po_file, "r", encoding="utf-8") as f:
        content = f.read()

    result = []
    i = 0
    lines = content.split("\n")
    count = 0

    while i < len(lines):
        line = lines[i]
        # Check for msgid line
        if line.startswith('msgid "') and not line.startswith('msgid ""'):
            # Collect full msgid value (may span multiple lines)
            msgid_val = line[7:]  # after 'msgid "'
            if msgid_val.endswith('"'):
                msgid_val = msgid_val[:-1]
            
            result.append(line)
            i += 1
            
            # Check for continuation lines
            while i < len(lines) and lines[i].startswith('"'):
                cont = lines[i]
                # Strip surrounding quotes
                inner = cont[1:-1] if cont.endswith('"') else cont[1:]
                msgid_val += "\n" + inner
                result.append(lines[i])
                i += 1
            
            # Unescape the msgid value for lookup
            msgid_unescaped = msgid_val.replace("\\n", "\n").replace('\\"', '"').replace("\\\\", "\\")
            
            # Now check if next non-empty line is msgstr ""
            # Skip blank lines and comments
            while i < len(lines) and (lines[i] == "" or lines[i].startswith("#")):
                result.append(lines[i])
                i += 1
            
            if i < len(lines) and lines[i] == 'msgstr ""':
                if msgid_unescaped in translations:
                    translation = translations[msgid_unescaped]
                    # Escape the translation for .po format
                    escaped_trans = translation.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
                    result.append(f'msgstr "{escaped_trans}"')
                    count += 1
                else:
                    result.append(lines[i])
                i += 1
            else:
                continue  # don't increment, already moved
        else:
            result.append(line)
            i += 1

    with open(po_file, "w", encoding="utf-8") as f:
        f.write("\n".join(result))

    print(f"  {po_file}: applied {count}/{len(translations)} translations")


